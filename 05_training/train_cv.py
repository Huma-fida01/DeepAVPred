"""Ten-fold cross-validation workflow for DeepAVPred.

The workflow requires an existing 1,040-column RECM-DWT matrix. Fold shuffling,
seed, early-stopping monitor, best-weight restoration, and model defaults are
configurable implementation settings.
"""

import argparse
import json
import os
import sys

import numpy as np
import tensorflow as tf
from sklearn.model_selection import StratifiedKFold


PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
MODEL_DIR = os.path.join(PROJECT_ROOT, "04_models", "DeepAVPred")
EVALUATION_DIR = os.path.join(PROJECT_ROOT, "06_evaluation")
sys.path.insert(0, MODEL_DIR)
sys.path.insert(0, EVALUATION_DIR)

from deepavpred_model import (  # noqa: E402
    BATCH_SIZE,
    EARLY_STOPPING_PATIENCE,
    MAX_EPOCHS,
    build_deepavpred,
    prepare_input_matrix,
)
from evaluate import compute_binary_metrics  # noqa: E402


def load_array(path):
    if not os.path.isfile(path):
        raise IOError(
            "Required input is missing: {0}. Supply an existing RECM-DWT "
            "feature matrix.".format(path)
        )
    if path.lower().endswith(".npy"):
        return np.load(path, allow_pickle=False)
    return np.loadtxt(path, delimiter=",")


def validate_labels(labels, sample_count):
    labels = np.asarray(labels).reshape(-1)
    if labels.shape[0] != sample_count:
        raise ValueError("Feature and label sample counts differ")
    if not np.all(np.isin(labels, (0, 1))):
        raise ValueError("Labels must contain only 0 and 1")
    return labels.astype(np.float32)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--features", required=True, help="Existing 1040-column .npy or CSV"
    )
    parser.add_argument("--labels", required=True, help="Existing binary-label .npy or CSV")
    parser.add_argument("--output-dir", default=os.path.join(PROJECT_ROOT, "outputs", "cv"))
    parser.add_argument("--first-units", type=int, default=128)
    parser.add_argument("--second-units", type=int, default=64)
    parser.add_argument("--dropout", type=float, default=0.3)
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--threshold", type=float, default=0.5)
    args = parser.parse_args()

    features = prepare_input_matrix(load_array(args.features))
    labels = validate_labels(load_array(args.labels), features.shape[0])
    os.makedirs(args.output_dir, exist_ok=True)

    splitter = StratifiedKFold(n_splits=10, shuffle=True, random_state=args.seed)
    fold_results = []
    for fold_number, (train_index, validation_index) in enumerate(
        splitter.split(features, labels), start=1
    ):
        tf.keras.backend.clear_session()
        tf.keras.utils.set_random_seed(args.seed + fold_number)
        model = build_deepavpred(
            first_bigru_units=args.first_units,
            second_bigru_units=args.second_units,
            dropout_rate=args.dropout,
            learning_rate=args.learning_rate,
        )
        early_stopping = tf.keras.callbacks.EarlyStopping(
            monitor="val_loss",
            patience=EARLY_STOPPING_PATIENCE,
            restore_best_weights=True,
        )
        model.fit(
            features[train_index],
            labels[train_index],
            validation_data=(features[validation_index], labels[validation_index]),
            epochs=MAX_EPOCHS,
            batch_size=BATCH_SIZE,
            callbacks=[early_stopping],
            verbose=2,
        )
        probabilities = model.predict(
            features[validation_index], batch_size=BATCH_SIZE, verbose=0
        ).reshape(-1)
        metrics = compute_binary_metrics(
            labels[validation_index], probabilities, threshold=args.threshold
        )
        metrics["fold"] = fold_number
        fold_results.append(metrics)
        model.save(os.path.join(args.output_dir, "fold_{0}.keras".format(fold_number)))
        np.save(
            os.path.join(args.output_dir, "fold_{0}_probabilities.npy".format(fold_number)),
            probabilities,
        )

    metric_names = [name for name in fold_results[0] if name != "fold"]
    summary = {
        name: {
            "mean": float(np.mean([fold[name] for fold in fold_results])),
            "standard_deviation": float(np.std([fold[name] for fold in fold_results])),
        }
        for name in metric_names
    }
    report = {
        "fold_generation": "Stratified folds generated by this run.",
        "folds": fold_results,
        "summary": summary,
    }
    with open(os.path.join(args.output_dir, "cv_metrics.json"), "w") as handle:
        json.dump(report, handle, indent=2, sort_keys=True)
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
